import path from "node:path";

import { parse as parseToml, stringify as stringifyToml } from "smol-toml";

import type {
  PackageContribution,
  PackageTransformContext,
  PresetDefinition,
} from "../../core/index.ts";
import { resolveReferencePackageDir } from "../../sources/index.ts";
import { resolveRustToolchainChannel } from "../roots.ts";

const encoder = new TextEncoder();
const decoder = new TextDecoder();

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function compareLockPackages(left: unknown, right: unknown): number {
  const leftRec = isRecord(left) ? left : {};
  const rightRec = isRecord(right) ? right : {};
  const leftName = typeof leftRec.name === "string" ? leftRec.name : "";
  const rightName = typeof rightRec.name === "string" ? rightRec.name : "";
  if (leftName !== rightName) {
    return leftName < rightName ? -1 : 1;
  }
  const leftVersion =
    typeof leftRec.version === "string" ? leftRec.version : "";
  const rightVersion =
    typeof rightRec.version === "string" ? rightRec.version : "";
  if (leftVersion !== rightVersion) {
    return leftVersion < rightVersion ? -1 : 1;
  }
  const leftSource = typeof leftRec.source === "string" ? leftRec.source : "";
  const rightSource =
    typeof rightRec.source === "string" ? rightRec.source : "";
  return leftSource < rightSource ? -1 : leftSource > rightSource ? 1 : 0;
}

function transformRustBinFiles(
  files: ReadonlyMap<string, PackageContribution>,
  context: PackageTransformContext,
): ReadonlyMap<string, PackageContribution> {
  const nextFiles = new Map(files);
  const crateName = context.instance.leafName;

  const cargoTomlEntry = files.get("Cargo.toml");
  if (cargoTomlEntry !== undefined) {
    const parsed = parseToml(decoder.decode(cargoTomlEntry.content));
    if (isRecord(parsed.package) && parsed.package.name === "app") {
      parsed.package.name = crateName;
    }
    nextFiles.set("Cargo.toml", {
      ...cargoTomlEntry,
      content: encoder.encode(stringifyToml(parsed)),
    });
  }

  const cargoLockEntry = files.get("Cargo.lock");
  if (cargoLockEntry !== undefined) {
    const parsed = parseToml(decoder.decode(cargoLockEntry.content));
    if (Array.isArray(parsed.package)) {
      const updatedPackages = parsed.package
        .map((pkg) => {
          if (isRecord(pkg) && pkg.source === undefined && pkg.name === "app") {
            return {
              ...pkg,
              name: crateName,
            };
          }
          return pkg;
        })
        .toSorted(compareLockPackages);
      const lockContent = `# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\n${stringifyToml(
        {
          ...parsed,
          package: updatedPackages,
        },
      )}`;
      nextFiles.set("Cargo.lock", {
        ...cargoLockEntry,
        content: encoder.encode(lockContent),
      });
    }
  }

  return nextFiles;
}

/** Builds the `rust-bin` preset backed by `@boringparts/reference-rust-bin`. */
export function createRustBinPreset(templatesRoot?: string): PresetDefinition {
  const packageDir = resolveReferencePackageDir(
    "@boringparts/reference-rust-bin",
    import.meta.url,
    templatesRoot,
  );
  const rustToolchainChannel = resolveRustToolchainChannel(templatesRoot);

  return {
    alias: "rust-bin",
    title: "Rust Binary",
    description:
      "Native Rust binary workspace with rustfmt, clippy, and cargo tests.",
    topology: "configurable-primary-package",
    nodes: [
      {
        nodeId: "binary",
        defaultName: "app",
        defaultPath: "crates/app",
        referencePackage: {
          packageName: "@boringparts/reference-rust-bin",
          packageDir,
          role: "native-package",
          publishable: false,
          resources: [
            { sourcePath: "resources/gitignore", targetPath: ".gitignore" },
          ],
          transformFiles: transformRustBinFiles,
          environment: (instance) => ({
            devcontainer: {
              layers: [
                {
                  id: "rust-toolchain",
                  dockerfilePath: path.join(
                    packageDir,
                    "resources",
                    "devcontainer",
                    "rust.Dockerfile",
                  ),
                },
              ],
              buildArgs: {
                RUST_TOOLCHAIN: rustToolchainChannel,
              },
              mounts: [
                {
                  type: "volume",
                  source: "${devcontainerId}-cargo-registry",
                  target: "/usr/local/cargo/registry",
                },
                {
                  type: "volume",
                  source: "${devcontainerId}-cargo-git",
                  target: "/usr/local/cargo/git",
                },
              ],
              containerEnv: {
                RUST_BACKTRACE: "1",
              },
            },
            vscode: {
              extensions: [
                "rust-lang.rust-analyzer",
                "tamasfe.even-better-toml",
              ],
              settings: {
                "rust-analyzer.cargo.features": "all",
                "rust-analyzer.check.command": "clippy",
                "rust-analyzer.linkedProjects": [`${instance.path}/Cargo.toml`],
                "rust-analyzer.procMacro.enable": true,
              },
            },
            dependabot: {
              updates: [
                {
                  packageEcosystem: "cargo",
                  directory: `/${instance.path}`,
                  interval: "weekly",
                },
                {
                  packageEcosystem: "rust-toolchain",
                  directory: `/${instance.path}`,
                  interval: "weekly",
                },
              ],
            },
          }),
        },
      },
    ],
  };
}
